"""자이로 CSV를 읽어서 도착 주기, 잡음(편향), 회전 각도를 확인한다.

사용법 (저장소 폴더 C:\\Users\\gyuyoung\\mobile_phone_camera 에서 실행):
    py -3.12 analysis\\gyro_check.py data\\gyro\\files\\gyro_20261009_171235.csv

    실제로 입력을 터미널에 해서 시스템경로를 제공해야함

입력: 앱의 [기록 시작/정지] 버튼이 만든 CSV. 한 줄 = 한 순간의 측정값
      timestamp_ns,x_rad_s,y_rad_s,z_rad_s
출력: 터미널에 숫자 요약 + analysis\\out\\ 폴더에 그래프(PNG)

[읽는 요령]  (코틀린 때와 같은 방식)
  [꼭 이해]  이 프로젝트의 핵심 아이디어
  [흐름]     큰 줄거리만 알면 됨
  [그냥 둠]  도구 설정이라 이해 안 해도 됨

[코틀린과 다른 점]  주석은 // 대신 #, 중괄호 { } 대신 "들여쓰기"로 덩어리를 나눈다.
"""
import sys
from pathlib import Path

import numpy as np          # numpy = 숫자 표(배열)를 빠르게 계산해주는 도구. 이 파일의 주인공
import matplotlib           # matplotlib = 그래프를 그려주는 도구

matplotlib.use("Agg")       # [그냥 둠] 그래프를 창으로 띄우지 않고 파일(PNG)로만 저장하겠다는 설정
import matplotlib.pyplot as plt

plt.rcParams["font.family"] = "Malgun Gothic"   # [그냥 둠] 그래프에 한글을 쓰기 위한 폰트 설정 (윈도우 기본 폰트)
plt.rcParams["axes.unicode_minus"] = False      # [그냥 둠] 마이너스 기호가 깨지지 않게


def main():
    # ---------------------------------------------------------------
    # 0. 어떤 파일을 읽을지 받는다
    # ---------------------------------------------------------------
    # [흐름] sys.argv = 터미널에서 이 파일을 실행할 때 뒤에 붙여 쓴 글자들의 목록.
    #        sys.argv[0]은 파일 이름 자신, sys.argv[1]이 우리가 적은 CSV 경로.
    if len(sys.argv) < 2:
        print("사용법: py -3.12 analysis\\gyro_check.py <csv 파일>")
        sys.exit(1)   # 파일 경로가 없으면 안내만 하고 끝낸다

    path = Path(sys.argv[1])   # Path = 파일 경로를 다루기 쉽게 감싼 것 (이름, 폴더 등을 꺼낼 수 있다)

    # ---------------------------------------------------------------
    # 1. CSV를 숫자 표로 읽는다
    # ---------------------------------------------------------------
    # [꼭 이해] np.loadtxt = CSV 파일을 읽어서 "숫자 표(2차원 배열)"로 만든다.
    #           data[행, 열] 로 값을 꺼낸다.  skiprows=1 은 맨 윗줄(제목줄)을 건너뛰라는 뜻.
    #           → data의 모양: (샘플 개수) 행 × 4열  [시각, x, y, z]
    data = np.loadtxt(path, delimiter=",", skiprows=1)
    if data.ndim != 2 or len(data) < 3:   # 값이 거의 없으면 계산이 의미 없어서 멈춘다
        print("값이 너무 적습니다 (3개 이상 필요)")
        sys.exit(1)

    # [꼭 이해] 열을 잘라서 쓴다. data[:, 0] = "모든 행의 0번째 열" (시각), data[:, 1:4] = "모든 행의 1~3번째 열" (x, y, z)
    #           시각은 나노초(ns)라서 1e9(=10억)로 나눠 초로 바꾸고, 첫 값을 0초로 맞춘다.
    t = (data[:, 0] - data[0, 0]) / 1e9    # 시각 (초)
    w = data[:, 1:4]                         # 각속도 x, y, z (rad/s)

    # ---------------------------------------------------------------
    # 2. 도착 주기: 값이 얼마나 일정하게 들어왔나
    # ---------------------------------------------------------------
    # [꼭 이해] np.diff = 이웃한 값끼리의 차이. 시각의 차이 = "값과 값 사이 간격".
    #           [0.000, 0.008, 0.016, ...] → [0.008, 0.008, ...]
    dt = np.diff(t)  # 간격 (초). 값이 N개면 간격은 N-1개
    print(f"파일: {path.name}")
    print(f"샘플 수: {len(t)}개, 길이: {t[-1]:.2f}초")
    # [흐름] f"...{값:.3f}" = 글자 안에 값을 끼워 넣는다. :.3f 는 소수점 3자리까지 (코틀린의 ${}와 비슷)
    print(f"평균 간격: {dt.mean() * 1000:.3f} ms  →  {1 / dt.mean():.1f} Hz")
    print(f"간격 표준편차: {dt.std() * 1000:.3f} ms  (작을수록 일정하게 도착)")
    print(f"간격 최소/최대: {dt.min() * 1000:.3f} / {dt.max() * 1000:.3f} ms")

    # ---------------------------------------------------------------
    # 3. 각속도의 평균(편향)과 표준편차(잡음)
    # ---------------------------------------------------------------
    # [꼭 이해] 평균(mean) = 값들의 가운데. 폰을 가만히 두고 기록했다면 이게 "센서가 원래 가진 치우침(편향)".
    #           표준편차(std) = 값이 평균에서 얼마나 흩어졌나. 가만히 둔 경우엔 "잡음의 크기".
    #           (움직인 기록에서는 움직임 때문에 표준편차가 커지는 게 정상이다)
    print("\n각속도 (rad/s)      평균(편향)    표준편차(잡음)")
    for i, name in enumerate("xyz"):   # [흐름] "xyz"의 글자를 하나씩 꺼내며 번호(i)도 같이 받는다: (0,"x"), (1,"y"), (2,"z")
        print(f"  {name}축            {w[:, i].mean():+.5f}      {w[:, i].std():.5f}")

    # ---------------------------------------------------------------
    # 4. 각속도를 쌓으면(적분) 회전 각도가 된다   ← 이 프로젝트의 핵심 아이디어
    # ---------------------------------------------------------------
    # [꼭 이해] 자동차로 비유: "속도 × 걸린 시간"을 계속 더하면 간 거리가 된다.
    #           마찬가지로 "각속도(rad/s) × 간격(초)"을 계속 더하면 돌아간 각도(rad)가 된다.
    #           이웃한 두 각속도의 평균을 쓰면(사다리꼴 방법) 더 정확하다.
    #
    # [흐름] w[1:]  = "두 번째 값부터 끝까지",  w[:-1] = "처음부터 마지막 직전까지"
    #        → 두 개를 나란히 놓으면 (이웃한 앞값, 뒷값) 쌍이 된다. 둘을 더해 2로 나누면 평균.
    # [그냥 둠] dt[:, None] = 간격(한 줄)을 세로로 세워서 x,y,z 세 열에 똑같이 곱하려고 모양을 맞추는 것
    step = (w[1:] + w[:-1]) / 2 * dt[:, None]   # 각 구간에서 새로 돌아간 각도 (rad)

    # [꼭 이해] np.cumsum = 누적합. [1, 2, 3] → [1, 3, 6]. 구간마다의 변화량을 위에서부터 계속 더해서
    #           "처음부터 지금까지 돌아간 총 각도"를 만든다. axis=0 은 "시간(위→아래) 방향으로".
    # [흐름] 맨 윗줄에는 "시작 각도 0"을 붙여서(np.vstack) 시각 배열 t와 길이를 맞춘다.
    angle = np.vstack([np.zeros(3), np.cumsum(step, axis=0)])   # 누적 회전 각도 (rad)
    deg = np.degrees(angle)                                     # 라디안 → 도(°) 로 바꿈 (1 rad ≈ 57.3°)

    print("\n회전 각도 (도)      마지막 값    가장 크게 돌아간 값")
    for i, name in enumerate("xyz"):
        # 마지막 값 = 기록이 끝났을 때의 각도. 돌렸다가 원위치로 되돌렸다면 0에 가까워야 한다
        # (남는 값 = 잡음이 쌓인 것 + 손으로 돌려서 자세가 조금 달라진 것)
        print(f"  {name}축            {deg[-1, i]:+8.2f}      {np.abs(deg[:, i]).max():8.2f}")

    # ---------------------------------------------------------------
    # 5. 그래프로 그린다
    # ---------------------------------------------------------------
    # [흐름] 위 그래프 = 자이로 원본(각속도), 아래 그래프 = 쌓아서 구한 각도. 시간축(가로)은 공유한다.
    out_dir = Path(__file__).parent / "out"   # 이 파일이 있는 폴더 안의 out 폴더
    out_dir.mkdir(exist_ok=True)              # 없으면 만든다
    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(10, 7), sharex=True)   # 위아래 2칸짜리 그림
    for i, name in enumerate("xyz"):
        ax1.plot(t, w[:, i], label=f"{name}축", linewidth=1)      # 가로: 시간, 세로: 각속도
        ax2.plot(t, deg[:, i], label=f"{name}축", linewidth=1.5)  # 가로: 시간, 세로: 각도
    ax1.set_ylabel("각속도 (rad/s)")
    ax1.set_title("자이로 원본 값 (폰이 돌고 있는 속도)")
    ax2.set_ylabel("회전 각도 (도)")
    ax2.set_xlabel("시간 (초)")
    ax2.set_title("각속도를 쌓아서(적분) 구한 회전 각도")
    for ax in (ax1, ax2):
        ax.grid(alpha=0.3)            # 눈금선
        ax.legend(loc="upper right")  # 범례 (x축, y축, z축 표시)
    fig.tight_layout()
    out_path = out_dir / (path.stem + ".png")   # path.stem = 확장자를 뺀 파일 이름
    fig.savefig(out_path, dpi=120)
    print(f"\n그래프 저장: {out_path}")


# [그냥 둠] "이 파일을 직접 실행했을 때만 main()을 돌려라"는 파이썬의 관례적인 한 줄.
# (다른 파일이 이 파일을 불러다 쓸 때는 자동으로 돌지 않게 하려는 것)
if __name__ == "__main__":
    main()
